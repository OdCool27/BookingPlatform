-- Add without rebuilding Bookings: UUID primary/foreign keys remain unchanged.
ALTER TABLE Bookings ADD COLUMN bookingReference TEXT
    CHECK (bookingReference IS NULL OR
           (length(bookingReference) = 6 AND bookingReference NOT GLOB '*[^0-9]*'
            AND bookingReference BETWEEN '100001' AND '999999'));

-- Normalize both legacy millisecond timestamps and ISO text for chronological backfill.
WITH numbered AS (
    SELECT bookingID, 100000 + ROW_NUMBER() OVER (
        ORDER BY CASE WHEN createdAt NOT GLOB '*[^0-9]*'
                      THEN datetime(CAST(createdAt AS INTEGER) / 1000, 'unixepoch')
                      ELSE datetime(createdAt) END, rowid
    ) AS reference FROM Bookings
)
UPDATE Bookings SET bookingReference = (
    SELECT CAST(reference AS TEXT) FROM numbered WHERE numbered.bookingID = Bookings.bookingID
);
CREATE UNIQUE INDEX uq_bookings_reference ON Bookings(bookingReference);

-- A permanent high-water mark survives booking deletion and application restarts.
CREATE TABLE BookingReferenceSequence (
    singleton INTEGER PRIMARY KEY CHECK (singleton = 1),
    lastReference INTEGER NOT NULL CHECK (lastReference BETWEEN 100000 AND 999999)
);
INSERT INTO BookingReferenceSequence VALUES
    (1, 100000 + (SELECT COUNT(*) FROM Bookings));

CREATE TRIGGER booking_reference_generated
BEFORE INSERT ON Bookings WHEN NEW.bookingReference IS NOT NULL
BEGIN
    SELECT RAISE(ABORT, 'Booking reference is generated by the database');
END;

CREATE TRIGGER booking_reference_allocate
AFTER INSERT ON Bookings
BEGIN
    SELECT CASE WHEN (SELECT lastReference FROM BookingReferenceSequence WHERE singleton = 1) >= 999999
        THEN RAISE(ABORT, 'Booking reference range exhausted') END;
    -- SQLite serializes writers. Allocation and assignment are part of the same insert transaction.
    UPDATE BookingReferenceSequence SET lastReference = lastReference + 1 WHERE singleton = 1;
    UPDATE Bookings SET bookingReference =
        (SELECT CAST(lastReference AS TEXT) FROM BookingReferenceSequence WHERE singleton = 1)
        WHERE bookingID = NEW.bookingID;
END;

CREATE TRIGGER booking_reference_immutable
BEFORE UPDATE OF bookingReference ON Bookings
WHEN OLD.bookingReference IS NOT NULL AND NEW.bookingReference IS NOT OLD.bookingReference
BEGIN
    SELECT RAISE(ABORT, 'Booking reference is immutable');
END;
